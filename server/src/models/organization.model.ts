import { Schema, model, type InferSchemaType } from 'mongoose';
import { userRef } from './_types';

const organizationSchema = new Schema(
  {
    name: { type: String, required: true, trim: true, maxlength: 160 },
    slug: { type: String, required: true, lowercase: true, trim: true, unique: true, index: true },
    createdBy: { ...userRef, required: true },
    plan: { type: String, enum: ['free', 'studio', 'agency'], default: 'studio' },
    currency: { type: String, default: 'USD', uppercase: true, maxlength: 3 },
    defaultHourlyRate: { type: Number, default: 75, min: 0 },
    /** Billing model applied to new projects unless overridden. */
    defaultBillingModel: { type: String, enum: ['fixed_price', 'hourly', 'daily', 'retainer'], default: 'fixed_price' },
    workingDays: { type: [Number], default: [1, 2, 3, 4, 5] },
    hoursPerPersonDay: { type: Number, default: 6, min: 1, max: 16 },
    timezone: { type: String, default: 'UTC' },
    /** Default revision allowance applied to new deliverables. */
    defaultRevisionRounds: { type: Number, default: 2, min: 0, max: 20 },
    approvalPolicy: {
      tokenTtlDays: { type: Number, default: 14, min: 1, max: 120 },
      /** Below this amount a project manager may send a change order without a second internal approval. */
      autoApproveUnderAmount: { type: Number, default: 0, min: 0 },
      requireEstimateBeforeInternalReview: { type: Boolean, default: true },
      /** When true, work cannot be logged as billable against an unapproved request (warning only). */
      warnOnUnapprovedWork: { type: Boolean, default: true },
    },
    ai: {
      /** Admins may switch the whole organization to deterministic-only mode. */
      enabled: { type: Boolean, default: false },
      provider: { type: String, enum: ['heuristic', 'openai', 'anthropic'], default: 'heuristic' },
      model: { type: String, default: '' },
      monthlyBudgetUsd: { type: Number, default: 25, min: 0 },
      /** When false, document text is not sent to any external provider. */
      allowDocumentText: { type: Boolean, default: false },
    },
    branding: {
      accentColor: { type: String, default: '#4f46e5' },
      logoUrl: { type: String, default: '' },
      documentFooter: { type: String, default: '' },
    },
    /** Agency-supplied contractual text inserted into change orders. Never generated by us. */
    termsText: { type: String, default: '', maxlength: 12000 },
    deletedAt: { type: Date, default: null },
    isDemo: { type: Boolean, default: false, index: true },
  },
  { timestamps: true, collection: 'organizations' },
);

export type OrganizationDoc = InferSchemaType<typeof organizationSchema>;
export const Organization = model('Organization', organizationSchema);
