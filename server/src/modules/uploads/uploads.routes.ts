import { Router } from 'express';
import multer from 'multer';
import { z } from 'zod';
import { asyncHandler } from '../../platform/http';
import { authenticate } from '../../middleware/auth';
import { requireOrg } from '../../middleware/tenant';
import { requirePermission } from '../../middleware/permission';
import { validate } from '../../middleware/validate';
import { verifyCsrf } from '../../middleware/csrf';
import { badRequest, notFound, unsupportedMedia } from '../../platform/errors';
import { payloadTooLarge } from './limits';
import { Document, Project, ChangeRequest, BaselineVersion } from '../../models';
import { sha256 } from '../../platform/crypto';
import { storage } from '../../platform/storage';
import { recordAudit } from '../../platform/audit';
import { AUDIT_ACTIONS, LIMITS } from '../../config/constants';
import { detectMime, extract, isAllowedUpload, suggestCandidateRequirements } from './extraction';
import { logger } from '../../platform/logger';

export const uploadsRouter = Router();
const mutating = [authenticate, verifyCsrf] as const;
uploadsRouter.use(authenticate, requireOrg);

/**
 * Uploads are held in memory, never written to disk by multer, because:
 *  - the storage key must be generated by us, never derived from the client's filename;
 *  - the bytes must be inspected (real MIME) before anything is persisted;
 *  - we compute the hash and run text extraction before the record exists, so a document is
 *    either fully described or not stored at all.
 */
const upload = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: LIMITS.maxUploadBytes, files: 1, fields: 20 },
});

function actorOf(req: Parameters<Parameters<typeof asyncHandler>[0]>[0]) {
  return {
    userId: req.auth!.userId,
    name: req.auth!.user.name,
    email: req.auth!.user.email,
    ip: req.ip,
    userAgent: req.header('user-agent'),
  };
}

uploadsRouter.post(
  '/projects/:projectId/documents',
  ...mutating,
  requirePermission('document.upload'),
  (req, res, next) => {
    upload.single('file')(req, res, (err: unknown) => {
      if (!err) return next();
      if (err instanceof multer.MulterError) {
        if (err.code === 'LIMIT_FILE_SIZE') return next(payloadTooLarge(`Files must be ${Math.round(LIMITS.maxUploadBytes / 1024 / 1024)} MB or smaller.`));
        return next(badRequest(`Upload rejected: ${err.message}.`));
      }
      logger.error('upload.middleware_failed', { error: String(err) });
      return next(badRequest('The upload could not be processed.'));
    });
  },
  validate({
    body: z.object({
      kind: z
        .enum(['proposal', 'statement_of_work', 'contract', 'requirement_source', 'request_evidence', 'other'])
        .optional(),
      clientId: z.string().optional(),
      requestId: z.string().optional(),
      note: z.string().max(500).optional(),
    }),
  }),
  asyncHandler(async (req, res) => {
    const orgId = req.org!.orgId;
    const project = await Project.findOne({ _id: String(req.params.projectId ?? ''), org: orgId, deletedAt: null });
    if (!project) throw notFound('Project not found.');

    const file = req.file;
    if (!file) throw badRequest('No file was received. Attach a file and try again.');

    // 1) Trust the bytes, not the browser's Content-Type.
    const sniffed = detectMime(file.buffer);
    const allowed = isAllowedUpload(sniffed.mime, file.size);
    if (!allowed.allowed) throw unsupportedMedia(allowed.reason ?? 'Unsupported upload.');

    // 1a) If the caller claims a specific structured format, the bytes must actually be that
    // format. A ".pdf" that is really a text file means something went wrong at the user's end,
    // and silently keeping it would put an unreadable document into the scope record.
    const claimed = (file.mimetype ?? '').toLowerCase();
    const claimedKind =
      claimed === 'application/pdf' ? 'pdf' : claimed.includes('wordprocessingml') ? 'docx' : claimed.startsWith('text/') ? 'text' : null;
    if (claimedKind && claimedKind !== sniffed.kind) {
      throw unsupportedMedia(
        `The file named "${file.originalname}" is not a real ${claimedKind === 'docx' ? 'Word document' : claimedKind.toUpperCase()} — its contents were detected as ${sniffed.mime}. Convert or re-export the file and upload it again.`,
      );
    }

    // 2) Extraction runs before persistence so the record is complete when it exists.
    const extraction = extract(file.buffer, sniffed.mime);

    // 3) Store under a generated key.
    const extension = sniffed.mime === 'application/pdf' ? '.pdf' : sniffed.mime.startsWith('text/') ? '.txt' : '.docx';
    const stored = await storage.put(file.buffer, { extension });

    const candidates = extraction.status === 'done' ? suggestCandidateRequirements(extraction.text) : [];

    const doc = await Document.create({
      org: orgId,
      project: project._id,
      client: req.body.clientId ?? project.client,
      kind: req.body.kind ?? 'requirement_source',
      originalName: file.originalname.slice(0, 300),
      storageKey: stored.key,
      detectedMime: sniffed.mime,
      claimedMime: (file.mimetype ?? '').slice(0, 160),
      sizeBytes: file.size,
      sha256: sha256(file.buffer),
      extractedText: extraction.status === 'done' ? extraction.text : null,
      extraction: {
        status: extraction.status,
        method: extraction.method,
        charCount: extraction.charCount,
        pageCount: extraction.pageCount,
        error: extraction.error,
        attemptedAt: new Date(),
        needsOcr: extraction.needsOcr,
      },
      extractionReview: {
        candidateRequirements: candidates,
        reviewedAt: null,
        appliedToBaseline: null,
        discarded: false,
      },
      linkedTo: req.body.requestId
        ? { type: 'request', id: req.body.requestId }
        : { type: 'project', id: project._id },
      uploadedBy: req.auth!.userId,
    });

    await recordAudit({
      org: orgId,
      action: AUDIT_ACTIONS.documentUploaded,
      actor: { kind: 'user', userId: req.auth!.userId, name: req.auth!.user.name, email: req.auth!.user.email },
      entity: { type: 'Document', id: String(doc._id), label: doc.originalName },
      meta: {
        project: String(project._id),
        kind: doc.kind,
        sizeBytes: file.size,
        detectedMime: sniffed.mime,
        claimedMime: file.mimetype,
        sha256: doc.sha256,
        extractionStatus: extraction.status,
        candidateCount: candidates.length,
      },
      ip: req.ip,
      userAgent: req.header('user-agent'),
    });

    res.status(201).json({
      document: {
        id: String(doc._id),
        originalName: doc.originalName,
        kind: doc.kind,
        sizeBytes: doc.sizeBytes,
        sha256: doc.sha256,
        detectedMime: doc.detectedMime,
        extraction: doc.extraction,
        // Nothing here is in the baseline yet. The reviewer decides what, if anything, becomes scope.
        reviewRequired: extraction.status === 'done' && candidates.length > 0,
        candidateCount: candidates.length,
      },
      notices: [
        ...(extraction.status === 'done' ? [] : [extraction.error || 'Text could not be extracted from this file.']),
        ...(sniffed.mime !== file.mimetype ? [`The file's real type (${sniffed.mime}) differs from what the browser reported (${file.mimetype}). We used the real type.`] : []),
        'Nothing has been added to the scope baseline. Suggested items are awaiting your review.',
      ],
    });
  }),
);

/** Review surface: candidate requirement lines extracted from a document. */
uploadsRouter.get(
  '/documents/:documentId/review',
  requirePermission('document.view'),
  asyncHandler(async (req, res) => {
    const doc = await Document.findOne({ _id: String(req.params.documentId ?? ''), org: req.org!.orgId, deletedAt: null })
      .select('+extractedText')
      .lean();
    if (!doc) throw notFound('Document not found.');
    res.json({
      document: {
        id: String(doc._id),
        originalName: doc.originalName,
        kind: doc.kind,
        detectedMime: doc.detectedMime,
        sizeBytes: doc.sizeBytes,
        sha256: doc.sha256,
        extraction: doc.extraction,
        review: doc.extractionReview,
        uploadedBy: doc.uploadedBy,
        createdAt: doc.createdAt,
      },
      excerpt: doc.extractedText ? doc.extractedText.slice(0, 4000) : null,
      candidates: doc.extractionReview?.candidateRequirements ?? [],
      guidance:
        'These lines were extracted verbatim from the document. They are suggestions only — check each one against the approved baseline before adding it to a draft version.',
    });
  }),
);

/** Marks the review as done (or discarded). Does not itself change any baseline. */
uploadsRouter.post(
  '/documents/:documentId/review',
  ...mutating,
  requirePermission('baseline.edit_draft'),
  validate({ body: z.object({ action: z.enum(['reviewed', 'discarded']), note: z.string().max(1000).optional() }) }),
  asyncHandler(async (req, res) => {
    const doc = await Document.findOne({ _id: String(req.params.documentId ?? ''), org: req.org!.orgId, deletedAt: null });
    if (!doc) throw notFound('Document not found.');

    type ReviewShape = {
      candidateRequirements?: unknown[];
      reviewedAt?: Date | null;
      appliedToBaseline?: unknown;
      discarded?: boolean;
    };
    const current: ReviewShape = (doc.extractionReview ?? {}) as ReviewShape;
    const appliedToBaseline = (current.appliedToBaseline ?? null) as import('mongoose').Types.ObjectId | null;
    doc.set('extractionReview', {
      candidateRequirements: current.candidateRequirements ?? [],
      reviewedAt: new Date(),
      reviewedBy: req.auth!.userId,
      appliedToBaseline,
      discarded: req.body.action === 'discarded',
    });
    await doc.save();

    const linkedBaseline = appliedToBaseline ? await BaselineVersion.findById(appliedToBaseline).lean() : null;

    res.json({
      reviewedAt: new Date(),
      discarded: req.body.action === 'discarded',
      appliedToBaseline: linkedBaseline ? { id: String(linkedBaseline._id), version: linkedBaseline.version } : null,
      note: req.body.note ?? '',
    });
  }),
);

/** Authorised, org-scoped download. There is no public URL for a stored document. */
uploadsRouter.get(
  '/documents/:documentId/download',
  requirePermission('document.view'),
  asyncHandler(async (req, res) => {
    const doc = await Document.findOne({ _id: String(req.params.documentId ?? ''), org: req.org!.orgId, deletedAt: null }).lean();
    if (!doc) throw notFound('Document not found.');
    const buffer = await storage.get(doc.storageKey);
    res.setHeader('Content-Type', doc.detectedMime);
    res.setHeader('Content-Disposition', `attachment; filename="${doc.originalName.replace(/"/g, '')}"`);
    res.setHeader('X-Document-Sha256', doc.sha256);
    res.send(buffer);
  }),
);

/** Soft delete: the bytes go, the audit trail stays. */
uploadsRouter.delete(
  '/documents/:documentId',
  ...mutating,
  requirePermission('document.delete'),
  asyncHandler(async (req, res) => {
    const doc = await Document.findOne({ _id: String(req.params.documentId ?? ''), org: req.org!.orgId, deletedAt: null });
    if (!doc) throw notFound('Document not found.');

    doc.deletedAt = new Date();
    await doc.save();
    try {
      await storage.remove(doc.storageKey);
    } catch (err) {
      logger.error('upload.delete_bytes_failed', { documentId: String(doc._id), error: String(err) });
    }

    await recordAudit({
      org: req.org!.orgId,
      action: AUDIT_ACTIONS.documentUploaded,
      actor: { kind: 'user', userId: req.auth!.userId, name: req.auth!.user.name, email: req.auth!.user.email },
      entity: { type: 'Document', id: String(doc._id), label: doc.originalName },
      changes: [{ field: 'deletedAt', from: '(active)', to: doc.deletedAt.toISOString() }],
      meta: { storageRemoved: true, sha256: doc.sha256 },
      ip: req.ip,
      userAgent: req.header('user-agent'),
    });

    res.json({ deletedAt: doc.deletedAt });
  }),
);

uploadsRouter.get(
  '/projects/:projectId/documents',
  requirePermission('document.view'),
  asyncHandler(async (req, res) => {
    const docs = await Document.find({ org: req.org!.orgId, project: String(req.params.projectId ?? ''), deletedAt: null })
      .select('-extractedText')
      .sort({ createdAt: -1 })
      .limit(200)
      .lean();
    res.json({ documents: docs });
  }),
);

/** Requirement sources attached to a request (client evidence). */
uploadsRouter.get(
  '/requests/:requestId/documents',
  requirePermission('request.view'),
  asyncHandler(async (req, res) => {
    const docs = await Document.find({
      org: req.org!.orgId,
      'linkedTo.type': 'request',
      'linkedTo.id': String(req.params.requestId ?? ''),
      deletedAt: null,
    })
      .select('-extractedText')
      .lean();
    res.json({ documents: docs });
  }),
);

